"""The unit and meaning of every field a plan writes: the one table `schema_doc` reads.

A path is as `schema_doc` normalizes it: `<workload>` and its kin stand for a map's keys, `[]` for a
list's items. A number must name its unit; a field that is not a number leaves it empty.
"""

from __future__ import annotations

D = dict[str, tuple[str, str]]


def _both(table: D, prefix: str, what: str) -> None:
    """requests and limits, each with cpu and memory_gib."""
    for kind in ("requests", "limits"):
        table[f"{prefix}.{kind}"] = ("", f"{what} {kind}")
        table[f"{prefix}.{kind}.cpu"] = ("vCPU", f"{kind} CPU")
        table[f"{prefix}.{kind}.memory_gib"] = ("GiB", f"{kind} memory")


def _pod(table: D, prefix: str, what: str) -> None:
    """A workload or component: replicas and the chart's per-pod resources."""
    table[prefix] = ("", f"{what}")
    table[f"{prefix}.replicas"] = ("pods", "the replicas the plan sizes, which the chart values apply (the regime's count when it fixed them)")
    table[f"{prefix}.min"] = ("pods", "the autoscaler's floor")
    table[f"{prefix}.max"] = ("pods", "the autoscaler's ceiling, reported and never reserved in the totals")
    _both(table, prefix, "per pod")


def _sums(table: D, prefix: str, nodes: bool) -> None:
    """The namespace or a pool at the floor, the sized replicas and the ceiling."""
    table.setdefault(prefix, ("", "what the chart values run, at each replica count"))
    for phase, what in (("floor", "the autoscalers' floors"), ("sized", "the replicas the plan sized"), ("ceiling", "the autoscalers' ceilings")):
        table[f"{prefix}.{phase}"] = ("", f"the sums at {what}")
        table[f"{prefix}.{phase}.requests"] = ("", "summed requests")
        table[f"{prefix}.{phase}.requests.cpu"] = ("vCPU", "summed CPU requests, before overhead")
        table[f"{prefix}.{phase}.requests.memory_gib"] = ("GiB", "summed memory requests, before overhead")
        table[f"{prefix}.{phase}.limits"] = ("", "summed limits")
        table[f"{prefix}.{phase}.limits.cpu"] = ("vCPU", "summed CPU limits")
        table[f"{prefix}.{phase}.limits.memory_gib"] = ("GiB", "summed memory limits")
        table[f"{prefix}.{phase}.volume_gib"] = ("GiB", "persistent volume claims of the pods counted")
        if nodes:
            table[f"{prefix}.{phase}.nodes"] = ("nodes", "nodes of the pool's shape that carry the sums after overhead, never below the pool's floor")


