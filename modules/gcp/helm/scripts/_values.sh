# _values.sh — The two values files that every deploy applies, and their checks.
#
#   helm/values/langsmith-values.yaml            the base values, copied from
#                                                examples/langsmith-values.yaml
#   helm/values/langsmith-values-overrides.yaml  everything else in one file:
#                                                Terraform outputs, each enabled
#                                                feature, SmithDB, SSO, and
#                                                langsmith-values-local.yaml last
#
# make init-values writes both files on every run. langsmith-values-local.yaml
# belongs to the operator, and no script writes it. Line 1 of a generated file
# holds the sha256 of the rest of the file, so a hand edit is found before a run
# overwrites it. The header of the overrides file records its inputs, so make
# deploy stops when terraform.tfvars, a module file, or the local file changed
# after the file was written.
#
# Sourced by init-values.sh, deploy.sh, status.sh and the values tests. The
# copies in modules/aws, modules/azure and modules/gcp are identical, and
# scripts/check.sh fails when they differ. Needs helm, awk, base64, and
# sha256sum or shasum. Runs on bash 3.2. The caller provides _parse_tfvar.
#
# Every step checks its own status: callers run these functions as `f || exit 1`,
# and bash ignores set -e inside a command that runs under || or &&.

_VALUES_BASE="langsmith-values.yaml"
_VALUES_OVERRIDES="langsmith-values-overrides.yaml"
_VALUES_LOCAL="langsmith-values-local.yaml"
_VALUES_DO_NOT_EDIT="Do not edit this file. Put your changes in $_VALUES_LOCAL, then run make init-values."

# _values_sha256 [<file>]: prints the hex sha256 of the file, or of stdin.
_values_sha256() {
  local sum
  if command -v sha256sum >/dev/null 2>&1; then
    sum=$(sha256sum ${1:+"$1"}) || return 1
  else
    sum=$(shasum -a 256 ${1:+"$1"}) || return 1
  fi
  printf '%s\n' "${sum%% *}"
}

# _values_merge <out> <helm values arguments>...
# Writes to <out> the values that Helm computes from -f, --set, --set-json and
# --set-string, with Helm's own rules: the files in order, then --set-json, then
# --set, then --set-string. A chart that renders only .Values does the merge, so
# no other YAML tool is needed. The keys come out sorted, with no comments.
_values_merge() (
  set -euo pipefail
  local out="$1" chart
  shift
  chart=$(mktemp -d) || return 1
  trap 'rm -rf "$chart"' EXIT
  mkdir "$chart/templates" || return 1
  printf 'apiVersion: v2\nname: langsmith-values\nversion: 0.1.0\n' > "$chart/Chart.yaml" || return 1
  printf '%s\n' '{{ toYaml .Values }}' > "$chart/templates/values.yaml" || return 1
  if ! helm template langsmith-values "$chart" "$@" > "$chart/rendered" 2> "$chart/err"; then
    echo "ERROR: helm could not merge the values files:" >&2
    sed 's/^/       /' "$chart/err" >&2
    return 1
  fi
  awk 'body { line[++n] = $0; if ($0 != "") last = n }
       /^# Source: / { body = 1 }
       END { for (i = 1; i <= last; i++) print line[i] }' "$chart/rendered" > "$out" || return 1
)

# _values_get <file>... -- <key>...
# Prints the value at a key path in the values that Helm computes from the files,
# for example: _values_get base.yaml overrides.yaml -- config hostname
# A key can contain dots, as annotation names do. Returns 1 when the path is
# missing or null, or holds a map or a list.
_values_get() (
  set -euo pipefail
  local arg chart path="" encoded
  local -a files=()
  while (( $# )); do
    arg="$1"
    shift
    [[ "$arg" != -- ]] || break
    files+=(-f "$arg")
  done
  (( $# )) || return 1
  for arg in "$@"; do
    arg=${arg//\\/\\\\}
    arg=${arg//\"/\\\"}
    path+="${path:+,}\"$arg\""
  done
  chart=$(mktemp -d) || return 1
  trap 'rm -rf "$chart"' EXIT
  mkdir "$chart/templates" || return 1
  printf 'apiVersion: v2\nname: langsmith-values-get\nversion: 0.1.0\n' > "$chart/Chart.yaml" || return 1
  # Helm reads every rendered document as a manifest, so the value goes out
  # inside a map, base64-encoded so that YAML quoting cannot change it. The "v"
  # prefix keeps an empty string apart from a missing value.
  cat > "$chart/templates/get.yaml" <<'TEMPLATE' || return 1
{{- $v := .Values -}}
{{- $found := true -}}
{{- range $k := .Values.langsmithValuesGetPath -}}
{{- if and $found (kindIs "map" $v) (hasKey $v $k) -}}
{{- $v = index $v $k -}}
{{- else -}}
{{- $found = false -}}
{{- end -}}
{{- end -}}
{{- if and $found (not (kindIs "invalid" $v)) (not (kindIs "map" $v)) (not (kindIs "slice" $v)) }}
{{ dict "langsmithValuesGet" (printf "v%s" (toString $v) | b64enc) | toYaml }}
{{- end -}}
TEMPLATE
  encoded=$(helm template langsmith-values-get "$chart" ${files[@]+"${files[@]}"} \
    --set-json "langsmithValuesGetPath=[$path]" | awk '/^langsmithValuesGet: / { print $2 }') || return 1
  [[ -n "$encoded" ]] || return 1
  encoded=$(printf '%s' "$encoded" | base64 --decode) || return 1
  printf '%s\n' "${encoded#v}"
)

# _values_seal <file> <title> <notes-file> <body-file>
# Writes <file> in one step, readable by its owner only: line 1 is the title and
# the sha256 of every line after it, then the notes as comments, then the body.
_values_seal() (
  set -euo pipefail
  local file="$1" title="$2" notes="$3" body="$4" tmp sum
  umask 077
  tmp=$(mktemp "$file.XXXXXX") || return 1
  trap 'rm -f "$tmp" "$tmp.rest"' EXIT
  { sed -e 's/^/# /' -e 's/^# $/#/' "$notes" && cat "$body"; } > "$tmp.rest" || return 1
  sum=$(_values_sha256 "$tmp.rest") || return 1
  { printf '# %s, sha256 %s\n' "$title" "$sum" && cat "$tmp.rest"; } > "$tmp" || return 1
  mv -f "$tmp" "$file" || return 1
)

# _values_seal_state <file>
# Prints missing; unsealed, when line 1 does not hold a sha256 (a file that no
# 0.18 make init-values wrote); edited, when the sha256 does not match; or intact.
_values_seal_state() {
  local file="$1" want got
  if [[ ! -f "$file" ]]; then
    echo missing
    return 0
  fi
  want=$(sed -n '1s/^# .*, sha256 \([0-9a-f]\{64\}\)$/\1/p' "$file")
  if [[ -z "$want" ]]; then
    echo unsealed
    return 0
  fi
  got=$(tail -n +2 "$file" | _values_sha256) || return 1
  if [[ "$got" == "$want" ]]; then echo intact; else echo edited; fi
}

# _values_notes <file> [<kind>]
# Prints the header notes of an overrides file without the leading "# ",
# optionally only the notes of one kind (their first word).
_values_notes() {
  awk -v kind="${2:-}" '
    NR == 1 { next }
    !/^#/ { exit }
    { sub(/^# ?/, ""); if (kind == "" || $1 == kind) print }
  ' "$1"
}

# ── Planning the overrides file ───────────────────────────────────────────────
# init-values.sh resets the plan, then adds each source in merge order. The
# arguments for Helm collect in _VALUES_PLAN_ARGS, and the header notes in the
# _VALUES_PLAN_* strings.

_values_plan_reset() {
  _VALUES_PLAN_ARGS=()
  _VALUES_PLAN_SOURCES=""
  _VALUES_PLAN_SETS=""
  _VALUES_PLAN_INPUTS=""
}

# _values_plan_file <example|generated|local> <file> [<label>]
#   example    a module file from helm/values/examples, recorded with its sha256
#   generated  a fragment that init-values.sh wrote; <label> says what it holds
#   local      langsmith-values-local.yaml, recorded with its sha256
_values_plan_file() {
  local kind="$1" file="$2" label="${3:-}" sum
  _VALUES_PLAN_ARGS+=(-f "$file")
  case "$kind" in
    example|local)
      sum=$(_values_sha256 "$file") || return 1
      _VALUES_PLAN_SOURCES+="  $kind ${file##*/} sha256 $sum"$'\n'
      ;;
    *)
      _VALUES_PLAN_SOURCES+="  generated ${label:-${file##*/}}"$'\n'
      ;;
  esac
}

# _values_plan_local <values_dir>: adds the local file when there is one.
_values_plan_local() {
  if [[ -f "$1/$_VALUES_LOCAL" ]]; then
    _values_plan_file local "$1/$_VALUES_LOCAL"
  else
    _VALUES_PLAN_SOURCES+="  local none"$'\n'
  fi
}

# _values_plan_set <--set|--set-string|--set-json> <key=value>
# Helm applies these after every file, so no values file can change them.
_values_plan_set() {
  _VALUES_PLAN_ARGS+=("$1" "$2")
  _VALUES_PLAN_SETS+="  set ${2%%=*}"$'\n'
}

# _values_plan_tfvars <key>...: records the terraform.tfvars value of each key,
# empty when the key is not set.
_values_plan_tfvars() {
  local key value
  for key in "$@"; do
    value=$(_parse_tfvar "$key" 2>/dev/null) || value=""
    _VALUES_PLAN_INPUTS+="  tfvar $key =${value:+ $value}"$'\n'
  done
}

# _values_plan_resolved <name> <value>: records a value that init-values.sh
# resolved from Terraform outputs, which deploy.sh resolves again and compares.
_values_plan_resolved() {
  _VALUES_PLAN_INPUTS+="  resolved $1 =${2:+ $2}"$'\n'
}

# _values_plan_script <module_dir> <path>...: records the sha256 of module
# scripts, by their path under the module directory.
_values_plan_script() {
  local module_dir="$1" path sum
  shift
  for path in "$@"; do
    sum=$(_values_sha256 "$module_dir/$path") || return 1
    _VALUES_PLAN_INPUTS+="  script $path sha256 $sum"$'\n'
  done
}

# _values_save_plan <dir>
# For the values tests: copies each file of the plan into <dir> and writes the
# Helm arguments to <dir>/args, one per line, so that a test can layer the same
# sources one by one and compare the result with the merged file.
_values_save_plan() {
  local dir="$1" arg n=0 file_next=0
  mkdir -p "$dir" || return 1
  : > "$dir/args" || return 1
  for arg in ${_VALUES_PLAN_ARGS[@]+"${_VALUES_PLAN_ARGS[@]}"}; do
    if (( file_next )); then
      n=$((n + 1))
      cp "$arg" "$dir/$n-${arg##*/}" || return 1
      arg="$dir/$n-${arg##*/}"
      file_next=0
    elif [[ "$arg" == -f ]]; then
      file_next=1
    fi
    printf '%s\n' "$arg" >> "$dir/args" || return 1
  done
}

# _values_render_overrides <file>: merges the plan into <file> and seals it.
# With LANGSMITH_VALUES_PLAN_DIR set, it also saves the plan there.
_values_render_overrides() (
  set -euo pipefail
  local file="$1" work
  work=$(mktemp -d) || return 1
  trap 'rm -rf "$work"' EXIT
  if [[ -n "${LANGSMITH_VALUES_PLAN_DIR:-}" ]]; then
    _values_save_plan "$LANGSMITH_VALUES_PLAN_DIR" || return 1
  fi
  _values_merge "$work/body" ${_VALUES_PLAN_ARGS[@]+"${_VALUES_PLAN_ARGS[@]}"} || return 1
  {
    echo "$_VALUES_DO_NOT_EDIT"
    echo "make deploy applies $_VALUES_BASE first, then this file."
    echo ""
    echo "Merged in this order, so a later source wins:"
    printf '%s' "$_VALUES_PLAN_SOURCES"
    if [[ -n "$_VALUES_PLAN_SETS" ]]; then
      echo "Then set from terraform.tfvars and Terraform outputs, after every file:"
      printf '%s' "$_VALUES_PLAN_SETS"
    fi
    echo "Inputs. make deploy stops when one of them differs:"
    printf '%s' "$_VALUES_PLAN_INPUTS"
    echo ""
  } > "$work/notes" || return 1
  _values_seal "$file" "$_VALUES_OVERRIDES, written by make init-values" "$work/notes" "$work/body" || return 1
)

# _values_render_base <example> <file>: copies the base values and seals the copy.
_values_render_base() (
  set -euo pipefail
  local example="$1" file="$2" work
  work=$(mktemp -d) || return 1
  trap 'rm -rf "$work"' EXIT
  printf '%s\n' "Copied from examples/${example##*/}. $_VALUES_DO_NOT_EDIT" > "$work/notes" || return 1
  _values_seal "$file" "$_VALUES_BASE, written by make init-values" "$work/notes" "$example" || return 1
)

# _values_write <values_dir> <examples_dir>
# Writes the base copy and the planned overrides into <values_dir>. Both are
# rendered first, so a failed merge changes neither file. When a file there was
# edited after make init-values wrote it, prints what the run would drop
# instead, writes nothing, and returns 1.
_values_write() (
  set -euo pipefail
  local dir="$1" examples="$2" work name tmp edited=""
  for name in "$_VALUES_BASE" "$_VALUES_OVERRIDES"; do
    [[ "$(_values_seal_state "$dir/$name")" != edited ]] || edited+="$name "
  done
  work=$(mktemp -d) || return 1
  trap 'rm -rf "$work"' EXIT
  _values_render_base "$examples/$_VALUES_BASE" "$work/$_VALUES_BASE" || return 1
  _values_render_overrides "$work/$_VALUES_OVERRIDES" || return 1
  if [[ -z "$edited" ]]; then
    for name in "$_VALUES_BASE" "$_VALUES_OVERRIDES"; do
      tmp=$(mktemp "$dir/.$name.XXXXXX") || return 1
      if ! cat "$work/$name" > "$tmp" || ! mv -f "$tmp" "$dir/$name"; then
        rm -f "$tmp"
        return 1
      fi
    done
    return 0
  fi
  for name in $edited; do
    echo "ERROR: $dir/$name was edited after make init-values wrote it." >&2
    echo "       This run would replace it. Lines marked + are only in your copy:" >&2
    diff -u "$work/$name" "$dir/$name" | tail -n +3 | head -n 60 | sed 's/^/         /' >&2 || true
  done
  echo "       Move your changes into $dir/$_VALUES_LOCAL, then delete the edited file" >&2
  echo "       and run make init-values again. Nothing was written." >&2
  return 1
)

# ── Checks ────────────────────────────────────────────────────────────────────

# _values_legacy_files <values_dir> <examples_dir>
# Prints each file in <values_dir> from the 0.17 layout, which a deploy no longer
# applies: every langsmith-values-*.yaml other than the overrides and local files,
# values.yaml and values-overrides.yaml, an overrides file that no 0.18 run wrote,
# and a base file that no 0.18 run wrote and that differs from the example.
_values_legacy_files() {
  local dir="$1" examples="$2" f name
  for f in "$dir"/*.yaml; do
    [[ -f "$f" ]] || continue
    name="${f##*/}"
    case "$name" in
      "$_VALUES_LOCAL"|langsmith-sandbox-values-overrides.yaml) ;;
      "$_VALUES_BASE")
        if [[ "$(_values_seal_state "$f")" == unsealed ]] && ! cmp -s "$f" "$examples/$name"; then
          echo "$name"
        fi
        ;;
      "$_VALUES_OVERRIDES")
        [[ "$(_values_seal_state "$f")" != unsealed ]] || echo "$name"
        ;;
      langsmith-values-*.yaml|values.yaml|values-overrides.yaml) echo "$name" ;;
    esac
  done
  return 0
}

# _values_legacy_stop <values_dir> <examples_dir>
# Returns 1, with the steps to move, while a file from the 0.17 layout is in
# <values_dir>. Each file is marked with what it is compared with its example.
_values_legacy_stop() {
  local dir="$1" examples="$2" files name note
  files=$(_values_legacy_files "$dir" "$examples")
  [[ -n "$files" ]] || return 0
  echo "ERROR: $dir holds values files from the 0.17 layout. From 0.18 a deploy applies only" >&2
  echo "       $_VALUES_BASE and $_VALUES_OVERRIDES, so nothing in these files applies:" >&2
  while IFS= read -r name; do
    case "$name" in
      "$_VALUES_OVERRIDES"|values-overrides.yaml)
        note="written by make init-values on 0.17; check it for changes you made by hand" ;;
      *)
        if [[ ! -f "$examples/$name" ]]; then
          note="no example of this name; check it for changes you made"
        elif cmp -s "$dir/$name" "$examples/$name"; then
          note="same as examples/$name"
        else
          note="differs from examples/$name, so it can hold your changes"
        fi
        ;;
    esac
    printf '         %-46s %s\n' "$name" "$note" >&2
  done <<< "$files"
  echo "       1) Move each change you made into $dir/$_VALUES_LOCAL." >&2
  echo "       2) Move the files above out of $dir, for example:" >&2
  echo "            mkdir -p ~/langsmith-values-0.17" >&2
  echo "            (cd \"$dir\" && mv $(tr '\n' ' ' <<< "$files")~/langsmith-values-0.17/)" >&2
  if grep -qx 'values-overrides.yaml' <<< "$files"; then
    echo "          values-overrides.yaml can hold plaintext secrets. Delete it when you no longer need it." >&2
  fi
  echo "       3) Run make init-values, then make deploy." >&2
  echo "       README.md, \"Move from the 0.17 values layout\", has the details." >&2
  return 1
}

# _values_drift <overrides> <module_dir> <values_dir>
# Prints one line for each input in the header of <overrides> that differs now:
# a terraform.tfvars value, an example file, a module script, or the local file.
_values_drift() {
  local overrides="$1" module_dir="$2" values_dir="$3" kind name rest old new sum
  local examples="$module_dir/helm/values/examples" local_file="$values_dir/$_VALUES_LOCAL"
  while read -r kind name rest; do
    case "$kind" in
      tfvar)
        old="${rest#=}"
        old="${old# }"
        new=$(_parse_tfvar "$name" 2>/dev/null) || new=""
        [[ "$old" == "$new" ]] || echo "terraform.tfvars has $name = \"$new\", and the file was written for \"$old\""
        ;;
      example)
        sum=$(_values_sha256 "$examples/$name" 2>/dev/null) || sum="none"
        [[ "$rest" == "sha256 $sum" ]] || echo "helm/values/examples/$name changed"
        ;;
      script)
        sum=$(_values_sha256 "$module_dir/$name" 2>/dev/null) || sum="none"
        [[ "$rest" == "sha256 $sum" ]] || echo "$name changed (a module upgrade)"
        ;;
      local)
        if [[ "$name" == none ]]; then
          [[ ! -f "$local_file" ]] || echo "$_VALUES_LOCAL was added"
        elif [[ ! -f "$local_file" ]]; then
          echo "$_VALUES_LOCAL was removed"
        else
          sum=$(_values_sha256 "$local_file") || sum="none"
          [[ "$rest" == "sha256 $sum" ]] || echo "$_VALUES_LOCAL changed"
        fi
        ;;
    esac
  done < <(_values_notes "$overrides")
}

# _values_resolved <overrides> <name>: prints the value that init-values.sh
# recorded for <name> with _values_plan_resolved, or nothing.
_values_resolved() {
  _values_notes "$1" resolved | awk -v n="$2" '$2 == n { sub(/^[^=]*= ?/, ""); print; exit }'
}

# _values_resolved_drift <overrides> <name=value>...
# Prints one line for each value that deploy.sh resolved again from Terraform
# outputs and that differs from the one recorded when the file was written.
_values_resolved_drift() {
  local overrides="$1" pair name want got
  shift
  for pair in "$@"; do
    name="${pair%%=*}"
    want="${pair#*=}"
    got=$(_values_resolved "$overrides" "$name")
    [[ "$got" == "$want" ]] || echo "Terraform now resolves $name to \"$want\", and the file was written for \"${got:-unset}\""
  done
}

# _values_check <module_dir> <values_dir>
# The checks make deploy runs before it touches the cluster. Prints each problem
# with its fix to stderr, and returns 1 when there is one.
_values_check() {
  local module_dir="$1" values_dir="$2" examples="$1/helm/values/examples" name state drift problem=0
  _values_legacy_stop "$values_dir" "$examples" || return 1
  for name in "$_VALUES_BASE" "$_VALUES_OVERRIDES"; do
    state=$(_values_seal_state "$values_dir/$name") || state=missing
    case "$state" in
      missing)
        echo "ERROR: $values_dir/$name not found. Run: make init-values" >&2
        problem=1
        ;;
      edited)
        echo "ERROR: $values_dir/$name was edited after make init-values wrote it." >&2
        echo "       Move the change into $_VALUES_LOCAL, delete the file, and run make init-values." >&2
        problem=1
        ;;
    esac
  done
  (( problem == 0 )) || return 1
  if ! tail -n +3 "$values_dir/$_VALUES_BASE" | cmp -s - "$examples/$_VALUES_BASE"; then
    echo "ERROR: helm/values/examples/$_VALUES_BASE changed after make init-values copied it. Run: make init-values" >&2
    return 1
  fi
  drift=$(_values_drift "$values_dir/$_VALUES_OVERRIDES" "$module_dir" "$values_dir")
  if [[ -n "$drift" ]]; then
    echo "ERROR: $_VALUES_OVERRIDES is out of date:" >&2
    sed 's/^/         /' <<< "$drift" >&2
    echo "       Run make init-values, then make deploy." >&2
    return 1
  fi
}

# _values_set_strings <overrides> <key=value>...
# Sets string values in a written overrides file and seals it again with the same
# notes. deploy.sh uses it when the load balancer hostname changes.
_values_set_strings() (
  set -euo pipefail
  local file="$1" pair work
  shift
  local -a args=(-f "$file")
  for pair in "$@"; do
    args+=(--set-string "$pair")
  done
  work=$(mktemp -d) || return 1
  trap 'rm -rf "$work"' EXIT
  _values_merge "$work/body" "${args[@]}" || return 1
  _values_notes "$file" > "$work/notes" || return 1
  _values_seal "$file" "$_VALUES_OVERRIDES, written by make init-values" "$work/notes" "$work/body" || return 1
)
