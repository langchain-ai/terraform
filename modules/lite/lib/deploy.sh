# Setting up, installing and removing a box: init, secrets, plan, up, install, down. Sourced by bin/lite.

cmd_init() {
  need terraform helm python3 ssh curl
  heading "init" "the tools are here; Terraform's providers next"
  local t
  for t in terraform helm python3; do field "$t" "$(bash -c "$(grep "^$t " <<<"$TOOLS" | cut -d' ' -f3-)")"; done
  printf '\n'
  start_log "$BUILD/logs"
  run terraform "terraform init in infra/" tf init -input=false "$@"
  [[ -f "$INFRA/terraform.tfvars" ]] || warn "no infra/terraform.tfvars yet: copy infra/terraform.tfvars.example and edit it."
  [[ -f "$SECRETS_FILE" ]] || warn "no license key saved yet: make secrets."
  next "make plan"
}

# The secrets Lite cannot generate, kept in infra/.secrets.env (mode 600, gitignored, where every module
# keeps them): the license key, and the
# Cloudflare Tunnel token for access = tunnel. A saved value is kept unless a new one is typed. Every
# other credential is generated by Terraform (infra/secrets.tf).
cmd_secrets() {
  heading "secrets" "kept in infra/.secrets.env, mode 600; every other credential is generated"
  local license tunnel tmp
  license="$(ask_secret LANGSMITH_LICENSE_KEY "LangSmith license key")"
  [[ -n "$license" ]] || fail "a license key is required."
  tunnel="$(ask_secret TUNNEL_TOKEN "Cloudflare Tunnel token (access = tunnel only; Enter to skip)")"
  umask 077
  tmp="$(mktemp "$SECRETS_FILE.XXXXXX")"
  {
    printf 'LANGSMITH_LICENSE_KEY=%s\n' "$license"
    if [[ -n "$tunnel" ]]; then printf 'TUNNEL_TOKEN=%s\n' "$tunnel"; fi
  } >"$tmp"
  mv "$tmp" "$SECRETS_FILE"
  field "saved" "infra/.secrets.env"
  next "make plan"
}

saved_secret() { [[ -f "$SECRETS_FILE" ]] && awk -F= -v k="$1" '$1 == k { sub(/^[^=]*=/, ""); print; exit }' "$SECRETS_FILE"; }

ask_secret() {
  local key="$1" prompt="  $2" current value
  current="$(saved_secret "$key" || true)"
  [[ -n "$current" ]] && prompt="$prompt [saved; Enter keeps it]"
  read -r -s -p "$prompt: " value
  printf '\n' >&2
  printf '%s' "${value:-$current}"
}

# Resolve the versions, plan into build/plan.out, and print what the plan does. Shared by plan and up.
plan_and_summarise() {
  need terraform helm python3 curl
  [[ -f "$INFRA/terraform.tfvars" ]] || fail "no infra/terraform.tfvars" "copy infra/terraform.tfvars.example to infra/terraform.tfvars and edit it."
  start_log "$BUILD/logs"
  resolve_versions
  umask 077
  rm -f "$PLAN_FILE"
  run plan "size the box and plan the change" tf plan -input=false -out="$PLAN_FILE" "$@"
  tf show -json "$PLAN_FILE" | python3 "$LITE/lib/summary.py"
}

cmd_plan() {
  heading "plan" "versions, sizes, and what would change"
  plan_and_summarise "$@"
  [[ "${VERBOSE:-}" == 1 ]] && tf show "$PLAN_FILE"
  next "make up"
}

cmd_up() {
  heading "up" "plan, apply, then install on the box"
  plan_and_summarise "$@"
  if [[ "${YES:-}" != 1 ]]; then
    local answer
    read -r -p "  Apply this plan and install it? [y/N] " answer
    [[ "$answer" == [yY]* ]] || fail "nothing changed." "make plan VERBOSE=1 shows every change."
  fi
  printf '\n'
  # The plan file holds the license key: applied and then removed.
  run apply "terraform apply" tf apply -input=false "$PLAN_FILE"
  rm -f "$PLAN_FILE"
  install_bundle
}

cmd_install() {
  heading "install" "the current plan, onto the box, without an apply"
  start_log "$BUILD/logs"
  install_bundle
}

# Send the bundle (Terraform's bundle output), the packaged datastores chart and the box's scripts over
# ssh, and run box/install.sh there as root. The bundle holds the generated credentials: written to a
# private temporary folder here, sent through ssh, and removed on exit; on the box it is kept under
# /var/lib/langsmith-lite (mode 700) and its Secrets file is deleted once applied.
install_bundle() {
  need terraform python3 ssh tar
  local work tgz
  ssh_from_outputs
  umask 077
  work="$(mktemp -d)"
  # Expanded now: a local is gone by the time EXIT runs, and set -u stopped the cleanup on it.
  # shellcheck disable=SC2064
  trap "rm -rf '$work'" EXIT
  mkdir "$work/bundle"
  run bundle "write the bundle" write_bundle "$work/bundle"
  tgz="$(awk -F= '$1 == "DATASTORES_TGZ" { print $2 }' "$work/bundle/lite.env")"
  [[ -f "$BUILD/charts/$tgz" ]] || fail "build/charts/$tgz is missing" "run make plan, which packages it."
  cp "$BUILD/charts/$tgz" "$LITE/lib/ui.sh" "$LITE/box/install.sh" "$LITE/box/checks.sh" "$work/bundle/"
  run ssh "reach $SSH_TARGET over ssh" wait_for_ssh
  run send "send it to $SSH_TARGET" send_bundle "$work"
  printf '\n  %son the box (sudo asks once; a first install takes 10 to 20 minutes)%s\n' "$DIM" "$OFF"
  # shellcheck disable=SC2016  # $? and $status expand on the box
  ssh_root 'sudo bash ~/.langsmith-lite/bundle/install.sh ~/.langsmith-lite/bundle; status=$?; rm -rf ~/.langsmith-lite; exit $status' \
    || fail "the install on the box stopped" "its message is above; make status shows the box."
  next "make access"
}

write_bundle() {
  tf_output bundle | python3 -c '
import json, os, sys
for name, content in json.load(sys.stdin).items():
    with open(os.path.join(sys.argv[1], name), "w") as f:
        f.write(content)
' "$1"
}

send_bundle() {
  tar -C "$1" -czf - bundle |
    ssh "${SSH_OPTS[@]}" "$SSH_TARGET" 'umask 077; rm -rf ~/.langsmith-lite && mkdir ~/.langsmith-lite && tar -xzf - -C ~/.langsmith-lite'
}

# Remove the install and every trace in it, after the install's name is typed.
#   aws        terraform destroy: the instance, its volume, its address, its security group
#   baremetal  k3s's uninstaller on the box (k3s, every volume, the bundle), then terraform destroy,
#              which forgets the generated credentials
cmd_down() {
  need terraform python3 ssh
  local name cloud typed
  name="$(tf_eval var.name)" || fail "could not read the install's name" "run make init first."
  cloud="$(tf_eval var.cloud)"
  heading "down" "delete $name and every trace in it"
  field "install" "$name"
  field "cloud" "$cloud"
  printf '\n'
  read -r -p "  Type the install's name to delete it: " typed
  [[ "$typed" == "$name" ]] || fail "nothing deleted" "the name did not match."
  printf '\n'
  start_log "$BUILD/logs"
  if [[ "$cloud" == baremetal ]]; then
    ssh_from_outputs
    printf '  %son the box (sudo asks once)%s\n' "$DIM" "$OFF"
    # Only a k3s Lite installed (its marker): never someone else's cluster.
    # shellcheck disable=SC2016  # expands on the box
    ssh_root 'if [ -e /etc/rancher/k3s/installed-by-langsmith-lite ]; then sudo /usr/local/bin/k3s-uninstall.sh >/dev/null; elif [ -e /etc/systemd/system/k3s.service ]; then echo "this k3s was not installed by Lite: left as it is"; exit 1; fi; sudo rm -rf /var/lib/langsmith-lite "$HOME/.kube/langsmith-lite.yaml"' \
      || fail "the uninstall on the box failed" "nothing else was removed."
    printf '  %-18s %sk3s and every volume removed from %s%s %sok%s\n' uninstall "$DIM" "$SSH_TARGET" "$OFF" "$GREEN" "$OFF"
  fi
  run destroy "terraform destroy" tf destroy -input=false -auto-approve
  rm -f "$PLAN_FILE" "$INFRA/resolved.auto.tfvars.json"
  printf '\n'
}
