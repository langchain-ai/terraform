# Setting up, installing and removing an install: secrets, plan, up, export, down. Sourced by bin/lite.

# The settings plan, up and preflight cannot run without (lib/settings.py asks for the missing ones at a
# terminal). YES=1, or no terminal, asks nothing: what is missing fails, naming what to pass.
settings() {
  need terraform python3
  local interactive=() colour=""
  [[ -t 0 && "${YES:-}" != 1 ]] && interactive=(--interactive)
  [[ -n "$GREEN" ]] && colour=1
  LITE_COLOR="$colour" python3 "$LITE/lib/settings.py" "$INFRA/terraform.tfvars" "${interactive[@]+"${interactive[@]}"}" || exit 1
}

# The license key, for plan and up: asked at a terminal when none is saved. preflight never needs it,
# and asking for it there stopped a read-only check of a machine.
license() {
  [[ -z "$(saved_secret LANGSMITH_LICENSE_KEY || true)" && -z "${TF_VAR_langsmith_license_key:-}" ]] || return 0
  [[ -t 0 && "${YES:-}" != 1 ]] || fail "no license key" "make secrets saves one, or set TF_VAR_langsmith_license_key."
  printf '\n'
  save_secrets
}

# The secrets Lite cannot generate, in infra/.secrets.env (mode 600, gitignored, where every module keeps
# them): the license key and the Cloudflare Tunnel token. A saved value is kept unless a new one is
# typed; every other credential is generated by Terraform (infra/secrets.tf).
cmd_secrets() {
  heading "secrets" "kept in infra/.secrets.env, mode 600; every other credential is generated"
  save_secrets
  next "make up"
}

save_secrets() {
  local license tunnel tmp
  license="$(ask_secret LANGSMITH_LICENSE_KEY "LangSmith license key")"
  [[ -n "$license" ]] || fail "a license key is required."
  tunnel="$(ask_secret TUNNEL_TOKEN "Cloudflare Tunnel token (access = tunnel only; Enter to skip)")"
  umask 077
  tmp="$(mktemp "$SECRETS_FILE.XXXXXX")"
  {
    printf 'LANGSMITH_LICENSE_KEY=%s\n' "$license"
    if [[ -n "$tunnel" ]]; then printf 'TUNNEL_TOKEN=%s\n' "$tunnel"; fi
  } >"$tmp"
  mv "$tmp" "$SECRETS_FILE"
  field "saved" "infra/.secrets.env"
}

saved_secret() { [[ -f "$SECRETS_FILE" ]] && awk -F= -v k="$1" '$1 == k { sub(/^[^=]*=/, ""); print; exit }' "$SECRETS_FILE"; }

ask_secret() {
  local key="$1" prompt="  $2" current value
  current="$(saved_secret "$key" || true)"
  [[ -n "$current" ]] && prompt="$prompt [saved; Enter keeps it]"
  read -r -s -p "$prompt: " value
  printf '\n' >&2
  printf '%s' "${value:-$current}"
}

# Shared by plan and up. PLAN_CHANGES counts the resources the plan adds, changes or destroys.
plan_and_summarise() {
  settings
  license
  need helm curl
  start_log "$BUILD/logs"
  resolve_versions
  umask 077
  rm -f "$PLAN_FILE"
  run plan "size the box and plan the change" tf plan -input=false -out="$PLAN_FILE" "$@"
  local json
  json="$(tf show -json "$PLAN_FILE")"
  python3 "$LITE/lib/summary.py" <<<"$json"
  PLAN_CHANGES="$(python3 -c 'import json,sys
print(sum(a in ("create", "update", "delete") for c in json.load(sys.stdin).get("resource_changes", []) for a in c["change"]["actions"]))' <<<"$json")"
}

# up applies the plan when there is anything to apply, then installs. The install is safe to run again,
# so up with nothing to apply repairs one that stopped halfway.
cmd_plan() {
  heading "plan" "versions, sizes, and what would change; nothing is changed"
  plan_and_summarise "$@"
  if [[ "${VERBOSE:-}" == 1 ]]; then tf show "$PLAN_FILE"; fi
  # The plan file holds the license key and every generated password; make up writes its own.
  rm -f "$PLAN_FILE"
  next "make up"
}

cmd_up() {
  heading "up" "plan, apply, then install"
  plan_and_summarise "$@"
  local cloud question="Apply this plan and install it?"
  cloud="$(tf_eval var.cloud)"
  ((PLAN_CHANGES)) || question="Nothing to apply. Install it again?"
  [[ "$cloud" == cluster ]] && question="${question/install it/write its files}"
  if [[ "${YES:-}" != 1 ]]; then
    local answer
    [[ -t 0 ]] || { rm -f "$PLAN_FILE"; fail "no terminal to ask: nothing changed" "YES=1 make up applies without asking."; }
    printf '\n'
    read -r -p "  $question [y/N] " answer
    # The plan file holds the license key and every generated password: not left behind on a no.
    [[ "$answer" == [yY]* ]] || { rm -f "$PLAN_FILE"; fail "nothing changed." "make plan VERBOSE=1 shows every change."; }
  fi
  printf '\n'
  ((PLAN_CHANGES == 0)) || run apply "terraform apply" tf apply -input=false "$PLAN_FILE"
  rm -f "$PLAN_FILE"
  if [[ "$cloud" == cluster ]]; then export_files; else install_bundle; fi
}

# The releases a box installs, without its own k3s, storage class or Traefik, written to OUT (default
# build/export/<name>) for a cluster of one's own (cloud = cluster) or as a copy of a box's.
cmd_export() {
  heading "export" "the releases, values and Secrets for a cluster of one's own"
  start_log "$BUILD/logs"
  export_files
}

export_files() {
  need terraform python3
  local name out
  name="$(tf_eval var.name)"
  out="${OUT:-$BUILD/export/$name}"
  umask 077
  mkdir -p "$out"
  run write "the releases into $out" write_export "$out"
  printf '\n'
  # Server-side: a client-side apply writes every Secret's value into its last-applied annotation.
  field "apply" "kubectl apply --server-side -f $out/cluster.yaml -f $out/secrets.yaml"
  field "then" "each line of $out/install.sh, in order"
  field "secrets" "$out/secrets.yaml holds every credential: mode 600, delete it once applied"
  next "bash $out/install.sh   (or the same releases through your own Helm or Argo CD)"
}

write_export() {
  local out="$1" tgz
  tf_output values >"$out/.values.json" && tf_output export >"$out/.export.json" || return 1
  tgz="$(python3 "$LITE/lib/export.py" "$out" "$out/.values.json" "$out/.export.json")" || return 1
  rm -f "$out/.values.json" "$out/.export.json"
  [[ -f "$BUILD/charts/$tgz" ]] || { echo "build/charts/$tgz is missing: run make up, which packages it"; return 1; }
  mkdir -p "$out/charts"
  cp "$BUILD/charts/$tgz" "$out/charts/"
}

# Send the bundle, the datastores chart and the box's scripts over ssh and run box/install.sh there. The
# bundle holds the generated credentials: a private temporary folder here, removed on exit; on the box
# /var/lib/langsmith-lite (mode 700), its Secrets file deleted once applied.
install_bundle() {
  need terraform python3 ssh tar
  local work tgz
  ssh_from_outputs
  umask 077
  work="$(mktemp -d)"
  # Expanded now: a local is gone by the time EXIT runs, and set -u stopped the cleanup on it.
  # shellcheck disable=SC2064
  trap "rm -rf '$work'" EXIT
  mkdir "$work/bundle"
  run bundle "write the bundle" write_bundle "$work/bundle"
  tgz="$(awk -F= '$1 == "DATASTORES_TGZ" { print $2 }' "$work/bundle/lite.env")"
  [[ -f "$BUILD/charts/$tgz" ]] || fail "build/charts/$tgz is missing" "run make up, which packages it."
  cp "$BUILD/charts/$tgz" "$LITE/lib/ui.sh" "$LITE/box/install.sh" "$LITE/box/checks.sh" "$work/bundle/"
  run ssh "reach $SSH_TARGET over ssh" wait_for_ssh
  run send "send it to $SSH_TARGET" send_bundle "$work"
  # shellcheck disable=SC2016  # $? and $status expand on the box
  ssh_root "k3s installs as a system service, and the data disk mounts: asked once, then the install runs (10 to 20 minutes the first time)" \
    'sudo bash ~/.langsmith-lite/bundle/install.sh ~/.langsmith-lite/bundle; status=$?; rm -rf ~/.langsmith-lite; exit $status' \
    || fail "the install on the box stopped" "its message is above; make status shows the box."
  next "make access"
}

write_bundle() {
  tf_output bundle | python3 -c '
import json, os, sys
for name, content in json.load(sys.stdin).items():
    with open(os.path.join(sys.argv[1], name), "w") as f:
        f.write(content)
' "$1"
}

send_bundle() {
  tar -C "$1" -czf - bundle |
    ssh "${SSH_OPTS[@]}" "$SSH_TARGET" 'umask 077; rm -rf ~/.langsmith-lite && mkdir ~/.langsmith-lite && tar -xzf - -C ~/.langsmith-lite'
}

# Remove the install and every trace in it, after its name is typed. On baremetal k3s's uninstaller
# runs on the box first; terraform destroy then forgets the generated credentials.
cmd_down() {
  need terraform python3 ssh
  local name cloud typed data_path
  name="$(tf_eval var.name)" || fail "could not read the install's name" "is anything installed? make up installs."
  cloud="$(tf_eval var.cloud)"
  heading "down" "delete $name and every trace in it"
  field "install" "$name"
  field "cloud" "$cloud"
  printf '\n'
  # A script confirms with CONFIRM=<name>; a person types it. YES=1 is not enough to delete data.
  typed="${CONFIRM:-}"
  [[ -n "$typed" ]] || read -r -p "  Type the install's name to delete it: " typed
  [[ "$typed" == "$name" ]] || fail "nothing deleted" "the name did not match."
  printf '\n'
  start_log "$BUILD/logs"
  if [[ "$cloud" == baremetal ]]; then
    ssh_from_outputs
    # Only a k3s Lite installed (its marker), never someone else's. k3s's uninstaller leaves a data_path
    # outside its own folder, so the volume folders go too and nothing else (security review, 2026-11-24:
    # the data stayed behind).
    data_path="$(tf_eval var.data_path)"
    # shellcheck disable=SC2016  # expands on the box
    ssh_root "k3s's uninstaller removes the service and every volume: asked once" \
      'if [ -e /etc/rancher/k3s/installed-by-langsmith-lite ]; then sudo /usr/local/bin/k3s-uninstall.sh >/dev/null; elif [ -e /etc/systemd/system/k3s.service ]; then echo "this k3s was not installed by Lite: left as it is"; exit 1; fi; sudo rm -rf /var/lib/langsmith-lite "$HOME/.kube/langsmith-lite.yaml" /etc/systemd/system/k3s.service.d/langsmith-lite-data.conf'"${data_path:+; sudo find '$data_path' -maxdepth 1 -name 'pvc-*' -exec rm -rf {} +}" \
      || fail "the uninstall on the box failed" "nothing else was removed."
    printf '  %-18s %sk3s and every volume removed from %s%s %sok%s\n' uninstall "$DIM" "$SSH_TARGET" "$OFF" "$GREEN" "$OFF"
  fi
  local volume=""
  [[ "$cloud" == aws ]] && volume="$(tf output -raw data_volume_id 2>/dev/null || true)"
  run destroy "terraform destroy" tf destroy -input=false -auto-approve
  rm -f "$PLAN_FILE" "$INFRA/resolved.auto.tfvars.json"
  # The daily snapshots outlive their policy and are billed until deleted; the docs said nothing was kept
  # (docs review, 2026-11-24).
  if [[ -n "$volume" ]]; then
    printf '\n'
    warn "the data volume's snapshots are kept, the last copy of every trace, and billed until deleted:"
    field "list them" "aws ec2 describe-snapshots --owner-ids self --filters Name=volume-id,Values=$volume --query 'Snapshots[].SnapshotId'"
    field "delete each" "aws ec2 delete-snapshot --snapshot-id <id>"
  fi
  printf '\n'
}
