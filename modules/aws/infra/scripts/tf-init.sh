# tf-init.sh — terraform init, with an optional S3 state backend.
#
# Usage (from terraform/aws/):
#   make init                           — same, through the Makefile
#   make init ARGS="-migrate-state"     — move existing state into the bucket
#   infra/scripts/tf-init.sh [terraform init flags]
#
# State stays local by default. To keep it in a bucket you own, copy
# infra/backend.hcl.example to infra/backend.hcl (git-ignored), fill it in, and
# run init. Terraform only accepts -backend-config for a backend that the
# configuration declares, and an empty backend block in a tracked file would
# break the local default. So when backend.hcl is present this script writes a
# git-ignored infra/backend_override.tf that declares an empty S3 backend, and
# passes backend.hcl to init. When backend.hcl is absent, it removes that file.
#
# An override file this script did not write is never overwritten or removed.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
INFRA_DIR="${INFRA_DIR:-$SCRIPT_DIR/..}"
BACKEND_HCL="$INFRA_DIR/backend.hcl"
OVERRIDE_TF="$INFRA_DIR/backend_override.tf"
MARKER="# Generated by scripts/tf-init.sh from backend.hcl. Do not edit; git-ignored."

if [[ -f "$BACKEND_HCL" ]]; then
  if [[ -f "$OVERRIDE_TF" ]] && ! grep -qF "$MARKER" "$OVERRIDE_TF"; then
    echo "ERROR: $OVERRIDE_TF exists and was not generated by tf-init.sh." >&2
    echo "       Move it aside, or remove infra/backend.hcl to keep your own backend setup." >&2
    exit 1
  fi
  printf '%s\nterraform {\n  backend "s3" {}\n}\n' "$MARKER" > "$OVERRIDE_TF"
  echo "Using the S3 state backend from infra/backend.hcl."
  exec terraform -chdir="$INFRA_DIR" init -backend-config=backend.hcl "$@"
fi

if [[ -f "$OVERRIDE_TF" ]] && grep -qF "$MARKER" "$OVERRIDE_TF"; then
  rm -f "$OVERRIDE_TF"
  echo "infra/backend.hcl is gone, so the generated S3 backend declaration was removed." >&2
  echo "If state already lives in the bucket, move it back with: make init ARGS=\"-migrate-state\"" >&2
fi
exec terraform -chdir="$INFRA_DIR" init "$@"
