#!/usr/bin/env bash
# Regression checks for tf-init.sh: when it passes backend.hcl to terraform init,
# when it writes and removes the generated backend_override.tf, and that it never
# touches an override file it did not write. Runs against a fake terraform that
# only records its arguments, so it needs no cloud access and no providers.
# Usage: bash modules/aws/infra/scripts/test-tf-init.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEST_TMP="$(mktemp -d)"
trap 'rm -rf "$TEST_TMP"' EXIT

mkdir -p "$TEST_TMP/bin" "$TEST_TMP/infra/scripts"
cp "$SCRIPT_DIR/tf-init.sh" "$TEST_TMP/infra/scripts/"
cat > "$TEST_TMP/bin/terraform" <<'EOF'
#!/usr/bin/env bash
echo "$*" > "$FAKE_TF_ARGS"
EOF
chmod +x "$TEST_TMP/bin/terraform"
export PATH="$TEST_TMP/bin:$PATH"
export FAKE_TF_ARGS="$TEST_TMP/args"

INFRA="$TEST_TMP/infra"
failures=0
check() { # check <name> <command...>: passes when the command succeeds
  local name="$1"
  shift
  if "$@"; then
    echo "  ok   $name"
  else
    echo "  FAIL $name"
    failures=$((failures + 1))
  fi
}
reset() { rm -f "$INFRA/backend.hcl" "$INFRA/backend_override.tf" "$FAKE_TF_ARGS"; }
run() { bash "$INFRA/scripts/tf-init.sh" "$@" 2>"$TEST_TMP/stderr"; }

echo "no backend.hcl: plain init, no override file"
reset
run -upgrade
check "passes flags through, no -backend-config" test "$(cat "$FAKE_TF_ARGS")" = "-chdir=$INFRA/scripts/.. init -upgrade"
check "writes no override file" test ! -e "$INFRA/backend_override.tf"

echo "backend.hcl present: S3 backend declared and configured"
reset
echo 'bucket = "b"' > "$INFRA/backend.hcl"
run -migrate-state
check "passes -backend-config=backend.hcl and the extra flags" grep -q -- "init -backend-config=backend.hcl -migrate-state" "$FAKE_TF_ARGS"
check "writes an empty s3 backend block" grep -q 'backend "s3" {}' "$INFRA/backend_override.tf"
check "marks the override as generated" grep -q "Generated by scripts/tf-init.sh" "$INFRA/backend_override.tf"

echo "backend.hcl removed: generated override is cleaned up"
rm -f "$INFRA/backend.hcl" "$FAKE_TF_ARGS"
run
check "removes the generated override" test ! -e "$INFRA/backend_override.tf"
check "tells the user how to move state back" grep -q -- "-migrate-state" "$TEST_TMP/stderr"
check "falls back to plain init" test "$(cat "$FAKE_TF_ARGS")" = "-chdir=$INFRA/scripts/.. init"

echo "hand-written backend_override.tf with backend.hcl: refuses, leaves it alone"
reset
echo 'bucket = "b"' > "$INFRA/backend.hcl"
printf 'terraform {\n  backend "gcs" {}\n}\n' > "$INFRA/backend_override.tf"
if run; then status=0; else status=$?; fi
check "exits non-zero" test "$status" -ne 0
check "does not overwrite it" grep -q 'backend "gcs"' "$INFRA/backend_override.tf"
check "does not run terraform" test ! -e "$FAKE_TF_ARGS"

echo "hand-written backend_override.tf, no backend.hcl: left alone"
reset
printf 'terraform {\n  backend "gcs" {}\n}\n' > "$INFRA/backend_override.tf"
run
check "does not remove it" grep -q 'backend "gcs"' "$INFRA/backend_override.tf"
check "runs a plain init" test "$(cat "$FAKE_TF_ARGS")" = "-chdir=$INFRA/scripts/.. init"

echo
if [[ "$failures" -ne 0 ]]; then
  echo "$failures check(s) failed."
  exit 1
fi
echo "All checks passed."
